"""Benchmark Phase 3B verified no-op versus legacy full replacement.

The target must be an explicitly confirmed disposable PostgreSQL database.
The replacement case is rolled back, but PostgreSQL WAL generated by the
transaction is intentionally measurable.
"""

from __future__ import annotations

import argparse
from decimal import Decimal
import json
import os
from pathlib import Path
import sys
import time

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from sqlalchemy import create_engine, func, select, text
from sqlalchemy.orm import Session

from backend.app.models import (
    CompetitorMatchSnapshot,
    CompetitorPriceList,
    CompetitorPriceListItem,
    CompetitorSourcePublication,
    CompetitorSourceVersion,
)
from backend.app.services.matching_cache.capture import (
    _postgres_io_sample,
    _wal_bytes_between,
    capture_and_publish_legacy_source_version,
)
from backend.app.services.matching_cache.source_noop import (
    source_semantic_metadata,
    validate_unchanged_source_import,
)
from backend.scripts.benchmark_matching_cache import _peak_rss_sampler, _postgres_load_sample


ITEM_COLUMNS = tuple(
    column.name for column in CompetitorPriceListItem.__table__.columns if column.name != "id"
)


def _synthetic_rows(row_count: int):
    for ordinal in range(1, row_count + 1):
        yield {
            "provisor_id": None,
            "provisor_goods_id": None,
            "filial_id": None,
            "name": "Synthetic Medicine 100 mg tablets N10",
            "reg_number": "",
            "distributor_goods_name": "Synthetic Medicine 100 mg tablets N10",
            "distributor_goods_id": f"SYN-{ordinal:09d}",
            "distributor_price": Decimal(100) + Decimal(ordinal % 100) / 100,
            "stock": 10,
            "package_count": 1,
            "expiry_date": "",
            "raw_name": "Synthetic Medicine 100 mg tablets N10",
            "raw_manufacturer": "Synthetic Factory",
            "raw_json": "{}",
        }


def _relation_sizes(db: Session) -> dict[str, int]:
    names = (
        "competitor_price_list_items",
        "competitor_source_versions",
        "competitor_source_version_items",
        "competitor_source_publications",
        "competitor_source_publication_items",
        "competitor_match_snapshots",
        "competitor_match_snapshot_items",
    )
    return {
        name: int(db.scalar(text("SELECT pg_total_relation_size(to_regclass(:name))"), {"name": name}) or 0)
        for name in names
    }


def _artifact_counts(db: Session, source_id: int) -> dict[str, int]:
    return {
        "sourceVersions": int(db.scalar(select(func.count(CompetitorSourceVersion.id)).where(
            CompetitorSourceVersion.competitor_price_list_id == source_id
        )) or 0),
        "publishedPublications": int(db.scalar(select(func.count(CompetitorSourcePublication.id)).where(
            CompetitorSourcePublication.competitor_price_list_id == source_id,
            CompetitorSourcePublication.status == "published",
        )) or 0),
        "snapshots": int(db.scalar(select(func.count(CompetitorMatchSnapshot.id)).join(
            CompetitorSourceVersion,
            CompetitorSourceVersion.id == CompetitorMatchSnapshot.source_version_id,
        ).where(CompetitorSourceVersion.competitor_price_list_id == source_id)) or 0),
    }


def run(*, database_url: str, source_id: int, expected_rows: int, mode: str) -> dict:
    engine = create_engine(database_url)
    try:
        with Session(engine) as db:
            if db.bind is None or db.bind.dialect.name != "postgresql":
                raise RuntimeError("PostgreSQL is required")
            version = int(db.scalar(text("SHOW server_version_num")))
            if not 160000 <= version < 170000:
                raise RuntimeError("PostgreSQL 16 is required")
            source = db.get(CompetitorPriceList, source_id)
            if source is None:
                raise RuntimeError(f"source {source_id} does not exist")
            if not str(source.source_key or "").startswith("phase2b3:synthetic:"):
                raise RuntimeError("benchmark refuses a source not labelled as Phase 2B.3 synthetic data")
            actual_rows = int(db.scalar(select(func.count(CompetitorPriceListItem.id)).where(
                CompetitorPriceListItem.price_list_id == source_id
            )) or 0)
            if actual_rows != expected_rows:
                raise RuntimeError(f"source row count mismatch: {actual_rows} != {expected_rows}")

            connection = db.connection()
            wal_before = str(connection.scalar(text("SELECT pg_current_wal_lsn()")))
            load_before = _postgres_load_sample(connection)
            io_before = _postgres_io_sample(db)
            sizes_before = _relation_sizes(db)
            artifacts_before = _artifact_counts(db, source_id)
            started = time.perf_counter()

            with _peak_rss_sampler() as memory:
                if mode == "noop":
                    decision = validate_unchanged_source_import(
                        db=db,
                        source=source,
                        incoming_rows=_synthetic_rows(expected_rows),
                        semantic_metadata_before=source_semantic_metadata(source),
                    )
                    if not decision.reusable:
                        raise RuntimeError(f"source was not reusable: {decision.reason}")
                    result = {
                        "reason": decision.reason,
                        "rowsInserted": 0,
                        "rowsUpdated": 0,
                        "rowsDeleted": 0,
                        "snapshotRebuildCount": 0,
                        "cacheInvalidations": 0,
                    }
                else:
                    columns_sql = ", ".join(ITEM_COLUMNS)
                    db.execute(text(
                        f"CREATE TEMP TABLE phase3b_incoming ON COMMIT DROP AS "
                        f"SELECT {columns_sql} FROM competitor_price_list_items "
                        "WHERE price_list_id=:source_id ORDER BY id"
                    ), {"source_id": source_id})
                    deleted = int(db.execute(text(
                        "DELETE FROM competitor_price_list_items WHERE price_list_id=:source_id"
                    ), {"source_id": source_id}).rowcount or 0)
                    inserted = int(db.execute(text(
                        f"INSERT INTO competitor_price_list_items ({columns_sql}) "
                        f"SELECT {columns_sql} FROM phase3b_incoming"
                    )).rowcount or 0)
                    capture = capture_and_publish_legacy_source_version(
                        db=db,
                        competitor_price_list_id=source_id,
                        source_metadata={"benchmark": "phase3b_replacement_rollback"},
                    )
                    if not capture.succeeded:
                        raise RuntimeError(f"replacement capture failed: {capture.reason}")
                    result = {
                        "reason": "legacy_full_replacement_rolled_back",
                        "rowsInserted": inserted,
                        "rowsUpdated": 0,
                        "rowsDeleted": deleted,
                        "snapshotRebuildCount": 0,
                        "cacheInvalidations": 1,
                    }

                elapsed = time.perf_counter() - started
                artifacts_during = _artifact_counts(db, source_id)
                db.rollback()

            with Session(engine) as measurement:
                measurement.execute(text("SELECT pg_stat_force_next_flush()"))
                wal_after = str(measurement.scalar(text("SELECT pg_current_wal_lsn()")))
                load_after = _postgres_load_sample(measurement.connection())
                io_after = _postgres_io_sample(measurement)
                sizes_after = _relation_sizes(measurement)
                wal_bytes = _wal_bytes_between(measurement, wal_before, wal_after)

            return {
                "dataset": "synthetic",
                "mode": mode,
                "sourceId": source_id,
                "rows": expected_rows,
                "durationSec": round(elapsed, 3),
                "rssStartMiB": round(int(memory["start"] or 0) / 1048576, 2),
                "rssPeakMiB": round(int(memory["peak"] or 0) / 1048576, 2),
                "walBytes": wal_bytes,
                "postgresLoadDelta": {
                    key: int(load_after[key]) - int(load_before[key]) for key in load_before
                },
                "postgresTempBytesDelta": (
                    int(io_after[1]) - int(io_before[1])
                    if io_before is not None and io_after is not None
                    else None
                ),
                "relationSizeDeltaBytes": {
                    key: int(sizes_after[key]) - int(sizes_before[key]) for key in sizes_before
                },
                "artifactsBefore": artifacts_before,
                "artifactsDuring": artifacts_during,
                **result,
            }
    finally:
        engine.dispose()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--database-url", default=os.getenv("TEST_POSTGRES_URL", ""))
    parser.add_argument("--source-id", type=int, required=True)
    parser.add_argument("--expected-rows", type=int, default=790_000)
    parser.add_argument("--mode", choices=("noop", "replacement-rollback"), required=True)
    parser.add_argument("--confirm-isolated", action="store_true")
    args = parser.parse_args()
    if not args.database_url:
        parser.error("--database-url or TEST_POSTGRES_URL is required")
    if not args.confirm_isolated:
        parser.error("--confirm-isolated is required")
    print(json.dumps(run(
        database_url=args.database_url,
        source_id=args.source_id,
        expected_rows=args.expected_rows,
        mode=args.mode,
    ), ensure_ascii=False, sort_keys=True))


if __name__ == "__main__":
    main()
